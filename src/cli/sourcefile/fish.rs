//! The fish sourcefile's own syntax: everything [`super::wrappers`] lays out, written as fish — and
//! laid out as bash's file is, so the two read alike: one function per line, each section a table.
//! Where bash puts a description in a trailing comment, fish sets it in the same place, with a
//! trailing `functions -d` — which fish shows beside the name when completing commands.

use std::collections::BTreeMap;

use super::{substitute, Section, Wrapper, BIN, ORIGINAL};
use crate::conf::keybinds::{self, Chord};
use crate::conf::RELOAD_EXIT_CODE;
use crate::support::align::align_columns;
use crate::support::shell_dialect::{fish_function, fish_original, printf_line, Shell, FISH_COLUMNS};

/// The file around `body`: the header, then bash's three early returns in fish's terms — before
/// anything is defined, cheapest first.
pub(super) fn file(body: &str) -> String {
    let mut out = String::from(
        "#!/usr/bin/env fish\n\
         # Auto-generated by `bashrs generate --shell fish` — do not edit.\n\
         # Regenerate by re-running COMPILE.sh.\n\
         # Loaded through bashrs.fish in fish's conf.d (~/.config/fish/conf.d), which the install writes;\n\
         # fish runs conf.d before config.fish.\n",
    );
    if body.is_empty() {
        return out;
    }
    // Fish reads conf.d for every fish it starts — scripts and `fish -c` included — so this guard
    // matters more than its bash twin: those must inherit nothing, above all not `python3`.
    out += "\nstatus is-interactive; or return 0  # interactive shells only — non-interactive contexts must inherit nothing\n";
    out += "if set -q _BASHRS_BARE; set -e _BASHRS_BARE; return 0; end  # shell_bare: skip bashrs for THIS shell, flag consumed (any new shell arms again)\n";
    out += &format!("test -f {BIN}; or return 0\n");
    out += &clear_completion_links(&super::defined_functions(body));
    out += body;
    out
}

/// The completion links of aliases named like one of `names`, cleared before the file defines its
/// functions. A fish alias is a function, which the file's own of the name replaces — fish's last
/// definition wins — but its link to the completions of what it wrapped (`--wraps`) outlives the
/// replacing: after `alias g=git`, bashrs's `g` would offer git's completions. `complete` with no
/// arguments lists the completions registered so far — at conf.d time, what earlier definitions
/// registered — so the links are found there: by a plain search for any, and only where there are
/// some by a regex of the names, which fish compiles at each use (~0.07 ms). Whole block, fish
/// 4.0.2 and 4.9.3: ~0.06 ms with no link registered, ~0.13 with some, ~0.3 with ten to clear.
///
/// Each is cleared by erasing its command's completions, which belonged to the replaced command
/// anyway — not by erasing the link by its target, which fish does for every command wrapping
/// that target: `alias g=git` cleared so would take git's completions from the user's own
/// `alias gti=git`. Fish 4.0 keeps the link through that erase, so there the completions stay
/// mixed, as they were before; 4.9 clears it.
///
/// Everything else keeps fish's own precedence. A function defined before the file is replaced
/// without a record, as any redefinition is; an abbreviation, which expands as it is typed, wins
/// wherever it is defined, and `shell_def` shows it first, with the `\NAME` that gets past it.
/// Rejected: setting those aside as bash's file sets its aliases aside — each earlier function
/// recorded, and each abbreviation erased and recorded, for `shell_def` to show. It cost ~0.4 ms
/// (fish 4.0.2) and ~0.3 ms (4.9.3) with nothing to set aside — 1.1 and 0.7 ms while it still
/// loaded fish's own functions to tell them apart, `diff.fish` running a `diff` — and it erased
/// abbreviations that take over no command (`--command`- and `--regex`-scoped ones).
fn clear_completion_links(names: &[&str]) -> String {
    let names: Vec<String> = names.iter().map(|name| regex::escape(name)).collect();
    let pattern = Shell::Fish.quote(&format!("^complete ({}) --wraps ", names.join("|")));
    format!(
        "\n# completion links of aliases named like the functions defined below (`alias g=git` has `g` complete as git), \
         cleared so that bashrs's commands complete as themselves\n\
         set -l __bashrs_links (complete | string match -e -- ' --wraps ')\n\
         set -q __bashrs_links[1]; and set __bashrs_links (string match -rg -- {pattern} $__bashrs_links)\n\
         for __bashrs_name in $__bashrs_links\n    \
         complete -c $__bashrs_name --erase  # by its name: erased by its target, a link is gone from every command that has it\n\
         end\n"
    )
}

/// The greeting, `text`, and — while an entry of `~/.bashrs` matches `archives` — the stale-config
/// `warning` on stderr: written in, printed by fish itself, in a terminal's first shell only — the
/// one leading its session, told from fish's own `/proc/$fish_pid/stat` without starting a process,
/// as bash's file tells it (`bash::greeting`, which says why the field is cut out exactly).
/// Unreadable, the file greets. The archives are matched by `set`, which a glob matching nothing
/// leaves empty — the one place it does: anywhere else, it fails its command.
pub(super) fn greeting(text: &str, warning: &str, archives: &str) -> String {
    format!(
        "set -l __bashrs_stat\n\
         test -r /proc/$fish_pid/stat; and read -l __bashrs_stat < /proc/$fish_pid/stat\n\
         if test -z \"$__bashrs_stat\"; or test (string replace -r -- '^.*\\) \\S+ \\S+ \\S+ (\\S+) .*$' '$1' $__bashrs_stat) = $fish_pid\n    \
         {}\n    \
         set -l __bashrs_old $HOME/.bashrs/{archives}\n    \
         set -q __bashrs_old[1]; and {} >&2\n\
         end\n",
        printf_line(text, Shell::Fish),
        printf_line(warning, Shell::Fish)
    )
}

/// One category's functions as a table: a wrapper for every name a command answers to, then the
/// pure-shell commands. Ahead of the table, each override that calls its original keeps it — a
/// statement, not a function, so no row: it holds a `;` too, and as a row its first statement
/// would set the width of the section's name column.
pub(super) fn definitions(section: &Section) -> String {
    let mut originals = String::new();
    let mut lines: Vec<String> = Vec::new();
    for wrapper in &section.wrappers {
        lines.extend(wrapper.names.iter().map(|name| wrapper_function(wrapper, name)));
    }
    for (name, body, comment) in &section.bodies {
        let description = Some(*comment).filter(|comment| !comment.is_empty());
        if body.fish().contains(ORIGINAL) {
            originals += &save_original(name);
            originals.push('\n');
        }
        lines.push(fish_function(name, description, &[substitute(body.fish(), Shell::Fish, name)]));
    }
    let table: String = align_columns(lines, &FISH_COLUMNS).into_iter().map(|line| line + "\n").collect();
    originals + &table
}

/// The function for one of `wrapper`'s names: the binary call, behind its probe and ahead of its
/// reload hook. The hook keeps the command's own exit status, as bash's does.
fn wrapper_function(wrapper: &Wrapper, name: &str) -> String {
    let description = wrapper.about.as_deref();
    let call = format!("{BIN} {} $argv", wrapper.real);
    let call = match wrapper.piped {
        None => call,
        Some(probe) => format!("{} | {call}", substitute(probe.fish(), Shell::Fish, name)),
    };
    let body = match wrapper.after {
        Some(hook) => vec![
            call,
            "set -l code $status".to_string(),
            format!("test $code -eq {RELOAD_EXIT_CODE}; and {hook}"),
            "return $code".to_string(),
        ],
        None => vec![call],
    };
    fish_function(name, description, &body)
}

/// Keeps fish's own definition of `name` as [`fish_original`] — once, so that sourcing the file
/// again never copies the override over its own original — or, where fish has no function of that
/// name to copy, stands the builtin in for it.
fn save_original(name: &str) -> String {
    let original = fish_original(name);
    format!(
        "functions -q {original}; or functions --copy {name} {original}; or function {original}; builtin {name} $argv; end  \
         # fish's own `{name}`, kept once for the override below to call"
    )
}

/// The keybinds: each of [`keybinds::bindings`] through [`keybinds::fish_bind`], commented with its
/// chord as a keyboard labels it and what it runs — bound by [`keybinds::fish_bind_helper`], which
/// goes again once they are, and run as typed through [`keybinds::fish_as_typed_helper`], which
/// stays for them.
pub(super) fn keybinds(abouts: &BTreeMap<String, String>) -> String {
    let binds: Vec<String> = keybinds::bindings()
        .iter()
        .map(|(key, func, run)| {
            let what = abouts.get(*func).map_or(*func, String::as_str);
            format!("{} # {}: {what}", keybinds::fish_bind(key, func, *run), Chord::parse(key).label())
        })
        .collect();
    let mut out = format!("\n# keybinds\n{}", keybinds::fish_bind_helper());
    for line in align_columns(binds, &["# "]) {
        out += &line;
        out.push('\n');
    }
    out += &format!("functions -e {}\n", keybinds::FISH_BIND);
    out += &keybinds::fish_as_typed_helper(keybinds::bindings());
    out
}

/// Completion, as bash's works: on TAB after a `-`, fish asks the binary for the command's flags
/// (`complete-flags`, always in sync with the real CLI) — in fish's form, each with its description,
/// which fish shows beside it. Any other word keeps fish's own completion, files for these. The
/// stainless aliases' flags, probed from each tool's `--help` at generate time, are listed instead,
/// bare, since that help says no more per flag than its name. Returns the section and the names it
/// completes.
///
/// A name fish completes already (it ships completions for `diff`, and for Mercurial's `hg` — as
/// files on its completion path, or, from fish 4.9, inside its binary) would get those loaded at
/// its first TAB, merged with these — so the install writes a file of bashrs's for each such name
/// into `~/.bashrs/fish_completions`, which this section puts first on `$fish_complete_path`: fish
/// loads the first file it finds there, and falls back to a built-in one only where it finds
/// none, so its own never run.
/// Rejected: loading fish's file at startup and erasing what it defined. Loading means running it,
/// and Mercurial's runs Mercurial — at every shell start, and with an error where it is missing.
///
/// Pure-shell commands and `python3` register nothing, keeping fish's own (`cd`'s directories,
/// python's flags) — as bash keeps its default completion for them.
pub(super) fn completion(sections: &[Section], stainless: &[(String, String)]) -> (String, Vec<String>) {
    let mut names: Vec<String> = sections
        .iter()
        .flat_map(|section| &section.wrappers)
        .flat_map(|wrapper| wrapper.names.iter().cloned())
        .collect();
    let section = format!(
        "\n# completion\n\
         #   Flags complete with their descriptions, asked of the binary at TAB-time as bash's are: type `-` and press <TAB>\n\
         #   e.g. `gg -<TAB>` lists gg's flags; `gg --de<TAB>` fills in `--delve`. Other words keep fish's own (file) completion.\n\
         #   Where fish has completions of its own for one of these names, the install puts a file of bashrs's in\n\
         #   {COMPLETIONS}, first on fish's search path, so fish loads it in place of its own.\n\
         if test -d \"{COMPLETIONS}\"; and not contains -- \"{COMPLETIONS}\" $fish_complete_path\n    \
         set -p fish_complete_path \"{COMPLETIONS}\"\n\
         end\n\
         {}\n\
         for name in {}\n    \
         complete -c $name -n {COMPLETING_FLAG} -a \"({BIN_ESCAPED} complete-flags $name)\"\n\
         end\n\
         {}",
        fish_function(COMPLETING_FLAG, Some("Whether the word being completed is a flag"), &["string match -q -- '-*' (commandline -ct)"]),
        names.join(" "),
        probed_completions(stainless),
    );
    names.extend(stainless.iter().map(|(alias, _)| alias.clone()));
    (section, names)
}

/// The condition every bashrs completion waits for: the word under the cursor is a flag.
const COMPLETING_FLAG: &str = "__bashrs_completing_flag";

/// [`BIN`] as it is written inside the double-quoted `-a` of a `complete` line: the quotes escaped,
/// and `$HOME` too, so it is expanded when fish completes rather than when the line registers.
const BIN_ESCAPED: &str = "\\\"\\$HOME/.bashrs/bashrs\\\"";

/// Where the install writes bashrs's completion files for the names fish completes too — as the
/// generated fish spells it, `$HOME` expanded at use time; `conf::fish_completions_dir` is the
/// Rust-side name of the same directory.
const COMPLETIONS: &str = "$HOME/.bashrs/fish_completions";

/// The stainless aliases' `complete` lines: each alias's probed flags offered once a `-` is typed.
fn probed_completions(stainless: &[(String, String)]) -> String {
    let lines = stainless
        .iter()
        .map(|(alias, flags)| format!("complete -c {alias} -n {COMPLETING_FLAG} -a {}", Shell::Fish.quote(flags)))
        .collect();
    align_columns(lines, &["-n "]).into_iter().map(|line| line + "\n").collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The probed flags are offered as one quoted list, once a `-` is typed, and the aliases'
    /// conditions line up.
    #[test]
    fn probed_flags_are_offered_once_a_dash_is_typed() {
        let rows = [("q".to_string(), "-h --help --explain".to_string()), ("ai_stop".to_string(), "--find".to_string())];
        let lines = probed_completions(&rows);
        let lines: Vec<&str> = lines.lines().collect();
        assert_eq!(lines[0], "complete -c q        -n __bashrs_completing_flag -a '-h --help --explain'");
        assert_eq!(lines[1], "complete -c ai_stop  -n __bashrs_completing_flag -a --find");
        assert_eq!(probed_completions(&[]), "", "no rows, no lines");
    }

    /// Keeping the original happens once, falling back to the builtin.
    #[test]
    fn the_original_is_saved_once_and_falls_back_to_the_builtin() {
        let saved = save_original("cd");
        assert!(
            saved.starts_with("functions -q __bashrs_original_cd; or functions --copy cd __bashrs_original_cd; or function __bashrs_original_cd; builtin cd $argv; end  # "),
            "{saved}"
        );
    }
}
